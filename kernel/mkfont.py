def rowbyte(s):
    s = (s + "        ")[:8]
    b = 0
    for i, ch in enumerate(s):
        if ch not in (' ', '.'):
            b |= (0x80 >> i)
    return b

# --- baseline normalisation ------------------------------------------------
# Hand-padding each glyph put uppercase/digits on a different baseline from
# lowercase, so text like "KiB" or "20f" looked half-subscripted. Rather than
# re-pad 95 glyphs by eye, every glyph is REANCHORED here to one baseline, so
# the exact padding above no longer matters. Each glyph is tagged with where
# it belongs vertically and its lit pixels are shifted to hit it.
#
#   base  - bottom of the glyph sits on the baseline (caps, digits, most)
#   desc  - has a tail below the baseline (g j p q y , ;)
#   asc   - reaches an ascender height but still bottoms on the baseline
#   top   - sits high (quotes, ^ `)
#   mid   - vertically centred (- = ~ + *)
#   under - the underscore, at the very bottom
BASELINE = 11

def anchor_of(code):
    ch = chr(code)
    if ch in "gjpqy,;":      return 'desc'
    if ch in "\"'`^":        return 'top'
    if ch in "-=~+*":        return 'mid'
    if ch == "_":            return 'under'
    return 'base'

def normalize(art):
    """Reposition a glyph's lit pixels onto the shared baseline."""
    lit = [r for r in range(len(art))
           if any(c not in (' ', '.') for c in art[r])]
    if not lit:
        return ["        "] * H          # blank glyph (space) - leave empty
    rmin, rmax = lit[0], lit[-1]
    block = art[rmin:rmax+1]
    a = anchor_of(0)                      # placeholder; set by caller
    return block, rmin, rmax

def place(code, art):
    block_info = normalize(art)
    if isinstance(block_info, list):
        return block_info                 # blank
    block, rmin, rmax = block_info
    h = len(block)
    anc = anchor_of(code)
    if   anc == 'top':   top = 1
    elif anc == 'mid':   top = (H - h) // 2
    elif anc == 'under': top = BASELINE + 2 - (h - 1)
    elif anc == 'desc':  top = (BASELINE + 2) - (h - 1)
    else:                top = BASELINE - (h - 1)   # base / asc
    if top < 0: top = 0
    if top + h > H: top = H - h
    canvas = ["        "] * H
    for i, row in enumerate(block):
        canvas[top + i] = row
    return canvas

